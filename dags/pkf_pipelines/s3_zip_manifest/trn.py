from __future__ import annotations

import csv
import shutil
from pathlib import Path

from pkf_runtime.kit import DataError, PackageContext, Runtime, TransientError, archive, naming, s3, unit_task


def build_manifest(entries: list[dict], dest: Path) -> Path:
    """Write manifest.csv from zip entries.

    Args:
        entries: zip entries as returned by archive.entries.
        dest: path of the manifest file to write.

    Returns:
        The path of the written manifest.
    """
    rows = [(e["name"], e["size"]) for e in entries if not e["is_dir"]]
    with open(dest, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n", quoting=csv.QUOTE_MINIMAL)
        writer.writerow(["file_name", "size_bytes"])
        writer.writerows(rows)
    return dest


def ensure_disk(path: Path, zip_size: int) -> None:
    """Guard the worker disk before downloading.

    Args:
        path: folder whose free space is checked.
        zip_size: size of the zip in bytes.

    Raises:
        TransientError: when free space is below 3 x zip size x 1.1.
    """
    need = int(zip_size * 3 * 1.1)
    free = shutil.disk_usage(path).free
    if free < need:
        raise TransientError(f"need {need} bytes, free {free}")


def _staging_done(ctx: PackageContext, rt: Runtime, client: object, stg_key: str) -> bool:
    """Check whether the staging zip already exists for this source.

    Args:
        ctx: the package context.
        rt: the runtime.
        client: the S3 client.
        stg_key: the staging key.

    Returns:
        True when the staging zip exists with the same source sha.

    Raises:
        DataError: when the staging zip exists for another source.
    """
    sh = s3.head(client, rt.settings["target_bucket"], stg_key)
    if not sh:
        return False
    if (sh.get("metadata") or {}).get("pkf-source-sha256") != ctx.vars["source_sha256"]:
        raise DataError(f"staging object {stg_key} exists for another source")
    ctx.artefacts["staging_key"] = stg_key
    ctx.vars["staged"] = True
    rt.log.info("staging zip %s already present; nothing to build", stg_key)
    return True


@unit_task("TRN-1")
def trn_1_build_the_manifest(ctx: PackageContext, rt: Runtime) -> PackageContext:
    """TRN-1: build manifest.csv and a rebuilt zip64 in shared_dir (R-TRN-1-a..e).

    Args:
        ctx: the package context.
        rt: the runtime.

    Returns:
        The context with artefacts.new_zip_path and vars.manifest_rows, or vars.staged.

    Raises:
        DataError: root manifest.csv present, unsafe zip, or foreign staging zip.
        TransientError: not enough free disk space.
    """
    client = rt.s3()
    src_bucket = rt.settings["source_bucket"]
    stg_key = naming.check_key(
        f"{rt.settings['staging_prefix']}{ctx.vars['stem']}_{ctx.vars['package_ts']}.zip"
    )
    if _staging_done(ctx, rt, client, stg_key):
        return ctx
    d = Path(rt.shared_dir())
    renamed = ctx.artefacts["renamed_key"]
    ph = s3.head(client, src_bucket, renamed)
    if not ph:
        raise DataError(f"processing copy {renamed} is missing")
    ensure_disk(d, int(ph["size"]))
    zp = s3.download(client, src_bucket, renamed, d / "in.zip")
    ents = archive.entries(zp)
    if any(e["name"] == "manifest.csv" for e in ents):
        raise DataError("package already contains a root manifest.csv")
    archive.safe_extract(zp, d / "x")
    m = build_manifest(ents, d / "manifest.csv")
    files = [(d / "x" / e["name"], e["name"]) for e in ents if not e["is_dir"]]
    out = archive.make_zip(files + [(m, "manifest.csv")], d / "out.zip")
    zp.unlink(missing_ok=True)
    rt.log.info("built %s with manifest.csv (%d rows)", out, len(files))
    ctx.artefacts["new_zip_path"] = str(out)
    ctx.vars["manifest_rows"] = len(files)
    return ctx


@unit_task("TRN-2")
def trn_2_upload_to_staging(ctx: PackageContext, rt: Runtime) -> PackageContext:
    """TRN-2: upload the rebuilt zip to staging with source metadata (R-TRN-2-a, R-TRN-2-b).

    Args:
        ctx: the package context.
        rt: the runtime.

    Returns:
        The context with artefacts.staging_key set.
    """
    if ctx.vars.get("staged"):
        rt.log.info("staging zip %s already present; upload skipped", ctx.artefacts.get("staging_key"))
        return ctx
    key = naming.check_key(
        f"{rt.settings['staging_prefix']}{ctx.vars['stem']}_{ctx.vars['package_ts']}.zip"
    )
    bucket = rt.settings["target_bucket"]
    s3.upload(
        rt.s3(),
        Path(ctx.artefacts["new_zip_path"]),
        bucket,
        key,
        if_exists="fail",
        metadata={
            "pkf-source-key": ctx.vars["source_key"],
            "pkf-source-sha256": ctx.vars["source_sha256"],
        },
    )
    rt.log.info("uploaded %s → s3://%s/%s", ctx.artefacts["new_zip_path"], bucket, key)
    ctx.artefacts["staging_key"] = key
    return ctx
