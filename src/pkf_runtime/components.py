"""Component modules: the Python code of a pipeline's trigger, source, transformation and destination.

`pkf build` writes one module per component into dags/pkf/<pipeline>/components/<kind>.py: the approved steps
(STEPS), the approved custom functions, and CUSTOM. The lock records each module's SHA-256; the runtime refuses to
run a module that differs (an edit in the dags folder never runs unapproved code).
"""
from __future__ import annotations

import hashlib
import pprint
from pathlib import Path

KINDS = ("trigger", "source", "transformation", "destination")
SIGNATURES = {"trigger": "(events, params, ctx) -> events", "source": "(groups, params, ctx, src) -> groups",
              "transformation": "(pkg, params, ctx) -> None", "destination": "(layout, params, ctx) -> layout; custom_delivery: (transfers, params, ctx, aws) -> results"}

_cache: dict[str, tuple[list[dict], dict]] = {}


def render_module(kind: str, name: str, steps: list[dict], functions: dict[str, str], header: list[str]) -> str:
    lines = [f'"""{kind.capitalize()} `{name}`: generated by package-factory from approved specs. Do not edit here.', "",
             *header, "", "Steps:", *[f"  {i}. {s['id']} [{s['op']}] {s.get('title', '')}" for i, s in enumerate(steps, 1)],
             f"Custom functions: {SIGNATURES[kind]}", '"""', "from __future__ import annotations", "",
             "KIND = " + repr(kind), "", "STEPS = " + pprint.pformat([{k: v for k, v in s.items() if k != "pseudocode"} for s in steps],
                                                                    sort_dicts=False, width=110), ""]
    for src in functions.values():
        lines += ["", src.strip("\n"), ""]
    lines += ["", "CUSTOM = {" + ", ".join(f'"{fn}": {fn}' for fn in functions) + "}", ""]
    return "\n".join(lines)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load(lock: dict, kind: str) -> tuple[list[dict], dict]:
    """(steps, custom functions) of one component, after checking the module is the approved one."""
    comp = (lock.get("components") or {}).get(kind)
    if comp is None:
        return [], {}
    path = Path(lock["_dir"]) / comp["module"]
    data = path.read_bytes()
    if sha256(data) != comp["sha256"]:
        raise PermissionError(f"{comp['module']} is not the approved {kind} code (SHA-256 differs from the lock); rebuild with `pkf build`")
    key = f"{path}:{comp['sha256']}"
    if key not in _cache:
        ns: dict = {"__name__": f"pkf_{lock['pipeline']['name']}_{kind}"}
        exec(compile(data, str(path), "exec"), ns)  # noqa: S102 - exactly the bytes whose hash was checked
        if ns.get("KIND") != kind:
            raise PermissionError(f"{comp['module']} is not a {kind} module")
        _cache[key] = (list(ns["STEPS"]), dict(ns.get("CUSTOM", {})))
    return _cache[key]
