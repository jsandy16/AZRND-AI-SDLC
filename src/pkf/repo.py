"""Load and validate a specs repository: six folders, one YAML file per component.

    pkf.toml
    triggers/<name>.yaml         sources/<name>.yaml             destinations/<name>.yaml
    transformations/<name>.yaml  connections/<name>.yaml         pipelines/<name>.yaml
    (designed components also have <name>.lock.yaml — plan, tests, approvals — and <name>.py — reviewed custom code)
    dags/                        generated by `pkf build`

Validation is deterministic: models (unknown keys rejected), file name = component name, references between
components, and template variables (every {name} must be a built-in or a parameter some layer defines).
"""
from __future__ import annotations

import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from pydantic import BaseModel, TypeAdapter, ValidationError

from . import yamlio
from .envelope import Issue, PfError
from .specs.common import BUILTIN_VARS, REQUIRED, template_fields
from .specs.destination import Destination
from .specs.pipeline import ConnectionFile, PipelineFile
from .specs.source import Source
from .specs.transformation import TransformationFile
from .specs.trigger import TriggerFile

MARKER = "pkf.toml"
FOLDERS = {"trigger": "triggers", "source": "sources", "destination": "destinations", "transformation": "transformations",
           "connection": "connections", "pipeline": "pipelines"}
MODELS: dict[str, Any] = {"trigger": TypeAdapter(TriggerFile), "source": TypeAdapter(Source), "destination": TypeAdapter(Destination),
                          "transformation": TypeAdapter(TransformationFile), "connection": TypeAdapter(ConnectionFile),
                          "pipeline": TypeAdapter(PipelineFile)}


def find_root(start: Path | None = None) -> Path:
    here = (start or Path.cwd()).resolve()
    for p in (here, *here.parents):
        if (p / MARKER).exists():
            return p
    raise PfError(f"not inside a package-factory repository (no {MARKER} above {here})", "no_repo")


def settings(root: Path) -> dict:
    cfg = tomllib.loads((root / MARKER).read_text(encoding="utf-8"))
    cfg.setdefault("staging", {}).setdefault("url", "file:///tmp/pkf-staging")
    cfg.setdefault("airflow", {}).setdefault("dags_folder", "dags")
    return cfg


@dataclass
class Repo:
    root: Path
    specs: dict[str, dict[str, BaseModel]] = field(default_factory=lambda: {k: {} for k in FOLDERS})
    raw: dict[str, dict[str, Any]] = field(default_factory=lambda: {k: {} for k in FOLDERS})
    issues: list[Issue] = field(default_factory=list)

    def file_of(self, kind: str, name: str) -> str:
        return f"{FOLDERS[kind]}/{name}.yaml"

    def get(self, kind: str, name: str) -> Any:
        if name not in self.specs[kind]:
            raise PfError(f"{kind} '{name}' not found (or invalid): {self.file_of(kind, name)}", "not_found",
                          [i for i in self.issues if i.file == self.file_of(kind, name)])
        return self.specs[kind][name]

    @property
    def ok(self) -> bool:
        return not any(i.severity == "error" for i in self.issues)

    def errors_for(self, kind: str, name: str) -> list[Issue]:
        return [i for i in self.issues if i.severity == "error" and i.file == self.file_of(kind, name)]


def _placeholders(node: Any, loc: str = "") -> list[str]:
    if isinstance(node, dict):
        return [x for k, v in node.items() for x in _placeholders(v, f"{loc}.{k}" if loc else str(k))]
    if isinstance(node, list):
        return [x for i, v in enumerate(node) for x in _placeholders(v, f"{loc}.{i}" if loc else str(i))]
    return [loc] if isinstance(node, str) and REQUIRED in node else []


def load(root: Path) -> Repo:
    repo = Repo(root)
    for kind, folder in FOLDERS.items():
        d = root / folder
        for f in sorted(d.glob("*.yaml")) if d.is_dir() else []:
            if f.name.endswith(".lock.yaml"):
                continue
            rel = f"{folder}/{f.name}"
            try:
                raw = yamlio.to_plain(yamlio.load(f))
            except Exception as exc:  # noqa: BLE001 - YAML syntax or aliases
                repo.issues.append(Issue(file=rel, msg=f"YAML error: {str(exc)[:300]}", code="yaml"))
                continue
            repo.raw[kind][f.stem] = raw
            holes = _placeholders(raw)
            for h in holes:
                repo.issues.append(Issue(file=rel, loc=h, msg="value not filled in yet", code="required"))
            if holes:
                continue
            try:
                spec = MODELS[kind].validate_python(raw)
            except ValidationError as exc:
                for e in exc.errors():
                    loc = ".".join(str(x) for x in e["loc"] if not (isinstance(x, str) and x in ("https", "sftp", "ftp", "s3", "local")))
                    repo.issues.append(Issue(file=rel, loc=loc, msg=e["msg"], code="invalid"))
                continue
            if spec.name != f.stem:
                repo.issues.append(Issue(file=rel, loc="name", msg=f"name '{spec.name}' must equal the file name '{f.stem}'", code="invalid"))
                continue
            if getattr(spec, "kind", kind) != kind:
                repo.issues.append(Issue(file=rel, loc="kind", msg=f"a {spec.kind} spec in the {folder}/ folder", code="invalid"))
                continue
            repo.specs[kind][spec.name] = spec
    repo.issues += cross_validate(repo)
    return repo


def available_vars(repo: Repo, pipeline: PipelineFile) -> set[str]:
    """Built-ins, every parameter layer, and the variables the trigger and source steps add (event_*, set_vars …)."""
    from .design import provided_vars

    conn = repo.specs["connection"].get(pipeline.connection) if pipeline.connection else None
    names = set(BUILTIN_VARS) | set(pipeline.params)
    parts = [("trigger", pipeline.trigger), ("transformation", pipeline.transformation),
             ("source", conn.source if conn else None), ("destination", conn.destination if conn else None)]
    for kind, cname in parts:
        spec = repo.specs[kind].get(cname) if cname else None
        if spec is not None:
            names |= set(getattr(spec, "params", {}) or {})
            if kind in ("trigger", "source"):
                names |= provided_vars(repo, kind, cname)
    return names


def _pending_design(repo: Repo, p: PipelineFile, conn) -> bool:
    """A trigger or source whose variables are not fully known: a requirement not planned yet, or custom steps (which
    may add variables of their own)."""
    from .design import load_lock, peek_steps

    for kind, cname in (("trigger", p.trigger), ("source", conn.source)):
        spec = repo.specs[kind].get(cname) if cname else None
        if spec is None:
            continue
        if getattr(spec, "requirement", None) and not load_lock(repo, kind, cname).get("plan"):
            return True
        if any(s["op"] == "custom" for s in (peek_steps(repo, kind, cname) or [])):
            return True
    return False


def cross_validate(repo: Repo) -> list[Issue]:
    out: list[Issue] = []
    S = repo.specs
    for name, c in S["connection"].items():
        f = repo.file_of("connection", name)
        if c.source not in S["source"]:
            out.append(Issue(file=f, loc="source", msg=f"source '{c.source}' not found in sources/", code="cross_ref"))
        if c.destination not in S["destination"]:
            out.append(Issue(file=f, loc="destination", msg=f"destination '{c.destination}' not found in destinations/", code="cross_ref"))
    for name, p in S["pipeline"].items():
        f = repo.file_of("pipeline", name)
        if p.connection is None:
            out.append(Issue(severity="warning", file=f, loc="connection", code="needs_split",
                             msg=f"no components yet: run `pkf plan pipeline {name}` to split the requirement"))
            continue
        conn = S["connection"].get(p.connection)
        if conn is None:
            out.append(Issue(file=f, loc="connection", msg=f"connection '{p.connection}' not found in connections/", code="cross_ref"))
            continue
        if p.trigger and p.trigger not in S["trigger"]:
            out.append(Issue(file=f, loc="trigger", msg=f"trigger '{p.trigger}' not found in triggers/", code="cross_ref"))
        if p.transformation and p.transformation not in S["transformation"]:
            out.append(Issue(file=f, loc="transformation", msg=f"transformation '{p.transformation}' not found in transformations/", code="cross_ref"))
        names = available_vars(repo, p)
        templates = [("pipeline", name, "package_name", p.package_name)]
        src, dst = S["source"].get(conn.source), S["destination"].get(conn.destination)
        if src:
            if src.requirement is None and src.steps is None:
                templates.append(("source", src.name, "extraction.root", src.extraction.root))
            if src.credentials.ref:
                templates.append(("source", src.name, "credentials.ref", src.credentials.ref))
        if dst:
            if dst.requirement is None and dst.steps is None:
                templates.append(("destination", dst.name, "delivery.prefix", dst.delivery.prefix))
            if dst.credentials.ref:
                templates.append(("destination", dst.name, "credentials.ref", dst.credentials.ref))
        for kind, cname, loc, tpl in templates:
            # {package} exists only once the package does (delivery); credentials see built-ins only, never run params
            allowed = (set(BUILTIN_VARS) - {"package"}) if loc == "credentials.ref" else \
                names if loc == "delivery.prefix" else names - {"package"}
            unknown = sorted(template_fields(tpl) - allowed)
            if unknown and _pending_design(repo, p, conn):
                out.append(Issue(severity="warning", file=repo.file_of(kind, cname), loc=loc, code="cross_ref",
                                 msg=f"template uses {unknown}; checked again once the trigger and source are planned"))
            elif unknown:
                out.append(Issue(file=repo.file_of(kind, cname), loc=loc, code="cross_ref",
                                 msg=f"template uses {unknown}, which is not available here for pipeline '{name}'"
                                     + (" (credential refs may use built-in variables only, e.g. {env})" if loc == "credentials.ref" else
                                        " ({package} exists only at delivery)" if "package" in unknown else " (add them to a params block)")))
    return out
