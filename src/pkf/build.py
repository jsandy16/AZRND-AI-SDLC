"""`pkf build` — turn a pipeline spec into an Airflow 3 DAG (deterministic: same specs → byte-identical files).

    dags/pkf_<pipeline>.py                         the DAG (thin: every task calls pkf_runtime.tasks)
    dags/pkf/<pipeline>/pipeline.lock.json         resolved specs, component module hashes, staging URL
    dags/pkf/<pipeline>/components/<kind>.py       trigger, source, transformation, destination: approved steps + code
    dags/.airflowignore                            keeps Airflow from parsing dags/pkf/

Tasks: check_source → check_destination → read_events → plan_packages → package[i] (mapped task group: extract →
t01…tNN → upload) → ack → report. A build is refused unless every component is approved and every pipeline example
passes end to end. A draft build (`pkf build --draft`, S4 review) also accepts code that passes its own tests but is
not approved yet, checks the same things and writes nothing: `dags/` only ever holds approved code.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import pkf_runtime
from pkf_runtime import components as comp
from pkf_runtime import simulate
from pkf_runtime.tasks import lock_digest

from . import VERSION, design
from .envelope import Issue, PfError
from .repo import FOLDERS, Repo, settings

HEADER = "# Generated by package-factory {v} from pipelines/{name}.yaml. Do not edit: change the specs and run `pkf build {name}`.\n"
SPEC_ONLY = {"requirement", "examples", "steps"}


def implicit_trigger(p) -> dict:
    return {"name": "schedule", "schedule": p.schedule, "connection": {}, "credentials": {"provider": "none"}, "params": {}}


SCHEDULE_STEPS = [{"id": "tick", "op": "schedule", "title": "One package per scheduled run", "params": {}}]


DRAFT_HEADER = "Code NOT approved yet: draft build for review (S4)"


def _approved_draft(repo: Repo, kind: str, name: str) -> dict:
    """`design.approved(..., allow_unapproved_code=True)` (K3). Falls back to the same rule here while the design
    module of this tree does not take the flag yet: `code_generated` is accepted like `approved` (the code's own tests
    pass; only the person's code approval is missing), any other non-approved stage is refused."""
    import inspect

    if "allow_unapproved_code" in inspect.signature(design.approved).parameters:
        return design.approved(repo, kind, name, allow_unapproved_code=True)
    st = design.status(repo, kind, name)
    if st["stage"] == "approved":
        return design.approved(repo, kind, name)
    if st["stage"] != "code_generated":
        raise PfError(f"{kind} '{name}' is not ready for a draft build ({st['stage']}): {st['next']}", "component_not_ready")
    spec = design.spec_of(repo, kind, name)
    lock = design.load_lock(repo, kind, name)
    steps = lock["plan"]["steps"]
    ids = design.custom_ids(steps)
    fns = design.extract_functions(design.code_path(repo, kind, name).read_text(encoding="utf-8"), ids) or {}
    header = ["Requirement (approved):", *("  " + ln for ln in (spec.requirement or "").strip().splitlines()),
              f"Plan approved by {lock['plan_approval']['by']} at {lock['plan_approval']['at']}", DRAFT_HEADER]
    return {"steps": steps, "functions": fns, "header": header}


def _getter(draft: bool, allow_unapproved_code: bool):
    if draft:
        return design.current
    if allow_unapproved_code:
        return _approved_draft
    return design.approved


def parts_for(repo: Repo, name: str, draft: bool = False, *, allow_unapproved_code: bool = False) -> dict:
    """The pipeline's four approved components: {kind: {"name", "spec", "steps", "functions", "header"}}.
    draft=True takes components as they stand (for `pkf test pipeline` while plans are under review).
    allow_unapproved_code=True (`pkf build --draft`, K3) also accepts components whose code passes its tests but is
    not approved yet (`code_generated`); every other stage is refused with `component_not_ready`."""
    get = _getter(draft, allow_unapproved_code)
    p = repo.get("pipeline", name)
    if p.connection is None:
        raise PfError(f"pipeline '{name}' has no components yet: pkf plan pipeline {name}", "not_ready")
    c = repo.get("connection", p.connection)
    out = {}
    if p.trigger:
        out["trigger"] = {"name": p.trigger, "spec": repo.get("trigger", p.trigger).model_dump(mode="json", exclude=SPEC_ONLY),
                          **get(repo, "trigger", p.trigger)}
    else:
        out["trigger"] = {"name": "schedule", "spec": implicit_trigger(p), "steps": SCHEDULE_STEPS, "functions": {},
                          "header": ["Implicit trigger: the pipeline's schedule"]}
    for kind, cname in (("source", c.source), ("destination", c.destination), ("transformation", p.transformation)):
        if cname is None:
            continue
        out[kind] = {"name": cname, "spec": repo.get(kind, cname).model_dump(mode="json", exclude=SPEC_ONLY),
                     **get(repo, kind, cname)}
    return out


def components_of(repo: Repo, name: str) -> list[tuple[str, str]]:
    """(kind, name) of every designed component the pipeline uses (the implicit schedule trigger is not one)."""
    p = repo.get("pipeline", name)
    if p.connection is None:
        return []
    c = repo.get("connection", p.connection)
    return [(k, n) for k, n in (("trigger", p.trigger), ("source", c.source), ("transformation", p.transformation),
                                ("destination", c.destination)) if n]


def unapproved_code(repo: Repo, name: str) -> list[str]:
    """`kind/name` of the pipeline's components whose code is tested but not approved (what a draft build accepts)."""
    out = []
    for kind, cname in components_of(repo, name):
        try:
            if design.status(repo, kind, cname)["stage"] == "code_generated":
                out.append(f"{kind}/{cname}")
        except PfError:
            continue
    return out


def _exec_functions(functions: dict[str, str]) -> dict:
    ns: dict = {}
    for src in functions.values():
        exec(compile(src, "<component>", "exec"), ns)  # noqa: S102 - approved, guarded code, for the end-to-end check only
    return {fn: ns[fn] for fn in functions}


def pipeline_examples(repo: Repo, name: str, parts: dict | None = None, draft: bool = False) -> list[dict]:
    """Every pipeline example through trigger → source → transformation → destination (in-memory)."""
    p = repo.get("pipeline", name)
    parts = parts or parts_for(repo, name, draft)
    sim = {k: {"steps": v["steps"], "custom": _exec_functions(v["functions"]), "params": v["spec"].get("params") or {}}
           for k, v in parts.items()}
    names = {"pipeline": name, "connection": p.connection, **{k: v["name"] for k, v in parts.items()}}
    sim.update(package_name=p.package_name, pipeline_params=p.params, names=names,
               source_bucket=(parts["source"]["spec"].get("connection") or {}).get("bucket"))
    return [{"example": e.name, **simulate.simulate_pipeline(sim, e.model_dump(mode="json"))} for e in p.examples]


def lock_for(repo: Repo, name: str, *, allow_unapproved_code: bool = False) -> tuple[dict, dict[str, bytes]]:
    """(lock, component module files). allow_unapproved_code: see parts_for (draft build, K3)."""
    p = repo.get("pipeline", name)
    errs = [i for i in repo.issues if i.severity == "error"]
    if errs:
        raise PfError("the specs have errors; run `pkf validate`", "invalid", errs[:20])
    parts = parts_for(repo, name, allow_unapproved_code=allow_unapproved_code)
    bad = [r for r in pipeline_examples(repo, name, parts) if r["status"] not in ("pass", "shown")]
    if bad:
        raise PfError(f"pipeline example(s) fail end to end: {[r['example'] for r in bad]} (pkf test pipeline {name})",
                      "pipeline_examples_failing",
                      [Issue(file=repo.file_of("pipeline", name), loc=f"examples.{r['example']}", msg=r["detail"], code="example_failed") for r in bad])
    if any(st["op"] == "custom_delivery" for st in parts["destination"]["steps"]):
        if parts["source"]["spec"].get("type") != "s3" or parts["destination"]["spec"].get("type") != "s3":
            raise PfError("a custom_delivery destination needs an S3 source and an S3 destination", "invalid")
        if "transformation" in parts:
            raise PfError("a custom_delivery destination copies straight from the source: the pipeline cannot have a transformation", "invalid")
        if p.max_active_runs != 1:
            raise PfError("a custom_delivery pipeline needs max_active_runs: 1 (two runs would move the same files)", "invalid")
    modules, components = {}, {}
    for kind, part in parts.items():
        rel = f"components/{kind}.py"
        data = comp.render_module(kind, part["name"], part["steps"], part["functions"], part["header"]).encode()
        compile(data, rel, "exec")
        modules[rel] = data
        components[kind] = {"name": part["name"], "module": rel, "sha256": comp.sha256(data),
                            "steps": [s["id"] for s in part["steps"]], "titles": [s.get("title", "") for s in part["steps"]]}
    c = repo.get("connection", p.connection)
    recv = parts["trigger"]["steps"][0]
    trigger = {**parts["trigger"]["spec"], "receive": {"op": recv["op"]}}
    if recv["op"] == "sqs" and p.max_active_runs != 1:
        raise PfError("an SQS-triggered pipeline needs max_active_runs: 1 (two runs would work on the same messages)", "invalid")
    lock = {
        "lock_version": 2, "framework_version": VERSION, "runtime_version": pkf_runtime.VERSION,
        "pipeline": p.model_dump(mode="json", exclude={"requirement", "examples"}), "connection": c.model_dump(mode="json"),
        "trigger": trigger, "source": parts["source"]["spec"], "destination": parts["destination"]["spec"],
        "transformation": ({"name": parts["transformation"]["name"], "params": parts["transformation"]["spec"].get("params") or {}}
                           if "transformation" in parts else None),
        "components": components, "staging_url": settings(repo.root)["staging"]["url"],
    }
    lock["lock_sha256"] = lock_digest(lock)  # checked by the runtime when the DAG loads
    return lock, modules


def _py(v) -> str:
    """A Python literal for v (repr of plain data is valid, escaped Python source)."""
    return repr(v)


def render_dag(lock: dict) -> str:
    p, c, comps = lock["pipeline"], lock["connection"], lock["components"]
    name = p["name"]
    sd = p["start_date"].split("-")
    trig = comps["trigger"]
    params = {}
    for k in ("source", "destination"):  # trigger parameters (e.g. the queue) are fixed, not run parameters
        params.update((lock.get(k) or {}).get("params") or {})
    params.update((lock.get("transformation") or {}).get("params") or {})
    params.update(p.get("params") or {})
    for k in (lock.get("trigger") or {}).get("params") or {}:  # not overridable by a run, so not a run parameter
        params.pop(k, None)
    t = comps.get("transformation")
    doc = [f'{p.get("description") or name}', "",
           f"- Trigger `{trig['name']}`: {', '.join(trig['steps'])}",
           f"- Source `{comps['source']['name']}` ({lock['source']['type']}) → destination `{comps['destination']['name']}` ({lock['destination']['type']}), connection `{c['name']}`",
           f"- Transformation: `{t['name']}` ({len(t['steps'])} step(s))" if t else "- Transformation: none (files delivered as extracted)",
           f"- Owner: {p['owner']}", "", "Each package (one per event) runs in its own branch of the `package` task group.",
           "Component code: dags/pkf/" + name + "/components/ (approved; checked by SHA-256 before it runs)."]
    out = [HEADER.format(v=VERSION, name=name), _py("\n".join(doc) + "\n"),
           "from __future__ import annotations", "", "import datetime", "", "import pendulum",
           "from airflow.sdk import Param, dag, get_current_context, task, task_group",
           "from airflow.sdk.exceptions import AirflowFailException", "", "from pkf_runtime import tasks as pkf", "",
           f"LOCK = pkf.load_lock(__file__, {_py(name)})", "", "",
           "def _ctx() -> dict:",
           "    c = get_current_context()",
           '    when = c.get("logical_date") or c["dag_run"].run_after',
           '    return {"run_id": c["run_id"], "logical_date": when, "params": dict(c["params"]), "conf": dict(c["dag_run"].conf or {})}',
           "", "",
           "def _run(fn, *args):",
           '    """Data and configuration problems fail at once; network problems use the task retries."""',
           "    try:", "        return fn(LOCK, *args, _ctx())", "    except pkf.FAIL_FAST as exc:",
           '        raise AirflowFailException(f"{type(exc).__name__}: {exc}") from None', "", ""]
    schedule = _py(lock["trigger"].get("schedule"))
    out += ["@dag(",
            f'    dag_id="pkf_{name}",',
            f"    description={_py((p.get('description') or name)[:200])},",
            f"    schedule={schedule},",
            f'    start_date=pendulum.datetime({int(sd[0])}, {int(sd[1])}, {int(sd[2])}, tz="UTC"),',
            "    catchup=False,",
            f"    max_active_runs={p['max_active_runs']},",
            f'    default_args={{"owner": {_py(p["owner"])}, "retries": {p["retries"]}, "retry_delay": datetime.timedelta(minutes={p["retry_delay_minutes"]})}},',
            "    params={" + ", ".join(f'{_py(k)}: Param({_py(v)}, type="string")' for k, v in sorted(params.items())) + "},",
            f"    tags={_py(['pkf', lock['source']['type'], *p.get('tags', [])])},",
            "    doc_md=__doc__,", ")",
            f"def pkf_{name}():"]
    body = []
    if c.get("check_before_run", True):
        body += ['    @task(task_id="check_source")', "    def check_source():", "        return _run(pkf.check_source)", "",
                 '    @task(task_id="check_destination")', "    def check_destination():", "        return _run(pkf.check_destination)", ""]
    body += ['    @task(task_id="read_events")', "    def read_events():", "        return _run(pkf.read_events)", "",
             '    @task(task_id="plan_packages")', "    def plan_packages():", "        return _run(pkf.plan_packages)", "",
             '    @task_group(group_id="package")', "    def package(spec):",
             '        @task(task_id="extract")', "        def extract(spec):", "            return _run(pkf.extract, spec)", ""]
    steps = t["steps"] if t else []
    groups = ([[i] for i in range(1, len(steps) + 1)] if p["task_split"] == "per_step" else [list(range(1, len(steps) + 1))]) if steps else []
    chain = ["        stage = extract(spec)"]
    for g in groups:
        tid = f"t{g[0]:02d}_{steps[g[0] - 1]}" if len(g) == 1 else "transform"
        title = t["titles"][g[0] - 1] if len(g) == 1 else f"{len(g)} transformation steps"
        body += [f'        @task(task_id="{tid}", doc_md={_py(title)})', f"        def {tid}(previous):",
                 f"            return _run(pkf.transform, {g}, previous)", ""]
        chain.append(f"        stage = {tid}(stage)")
    body += ['        @task(task_id="upload")', "        def upload(previous):", "            return _run(pkf.upload, previous)", "",
             *chain, "        return upload(stage)", "",
             '    @task(task_id="ack", trigger_rule="all_done")', "    def ack():", "        return _run(pkf.ack)", "",
             '    @task(task_id="report", trigger_rule="all_done")', "    def report():", "        return _run(pkf.report)", ""]
    wiring = ["    events = read_events()", "    planned = plan_packages()"]
    if c.get("check_before_run", True):
        wiring.append("    check_source() >> check_destination() >> events")
    wiring += ["    events >> planned", "    delivered = package.expand(spec=planned)", "    acked = ack()", "    delivered >> acked",
               "    acked >> report()"]
    return "\n".join(out + body + wiring + ["", "", f"pkf_{name}()", ""])


IGNORE_LINE = "pkf/**"


def _airflowignore(path: Path) -> bytes:
    """Keep whatever else is in .airflowignore; only make sure pkf/** is there."""
    text = path.read_text(encoding="utf-8") if path.exists() else "# package-factory: pipeline locks and transformation code are not DAG files\n"
    if IGNORE_LINE not in text.splitlines():
        text = text.rstrip("\n") + ("\n" if text.strip() else "") + IGNORE_LINE + "\n"
    return text.encode()


def warnings(repo: Repo, name: str, lock: dict) -> list[Issue]:
    """Build warnings (severity warning: they never fail a build; D18, D6, A11): settings that look meant for the DAG
    but are not used by it, a cron step that does not divide the hour, and a file:// staging URL (single machine only)."""
    f = f"pipelines/{name}.yaml"
    out: list[Issue] = []
    trig = lock.get("trigger") or {}
    tfile = f"triggers/{trig['name']}.yaml" if trig.get("name") and trig["name"] != "schedule" else f
    inert = sorted(k for k in (trig.get("params") or {}) if k == "retries" or k.startswith("retry_delay"))
    if inert:
        out.append(Issue(severity="warning", file=tfile, code="inert_trigger_param",
                         msg=f"trigger parameter(s) {', '.join(inert)} not used by the DAG: set retries / retry_delay_minutes in "
                             f"pipelines/{name}.yaml (Pipeline tab → Pipeline settings)"))
    cron = (trig.get("schedule") or "").split()
    if len(cron) == 5 and cron[0].startswith("*/") and cron[0][2:].isdigit() and int(cron[0][2:]) > 0 and 60 % int(cron[0][2:]):
        n = int(cron[0][2:])
        out.append(Issue(severity="warning", file=tfile, code="uneven_cron",
                         msg=f"schedule '{trig['schedule']}' runs at minutes divisible by {n} (not every {n} minutes): "
                             "the gap at the top of the hour is shorter"))
    url = lock.get("staging_url") or ""
    if url.startswith("file:"):
        out.append(Issue(severity="warning", file="pkf.toml", code="file_staging",
                         msg=f"staging is a local folder ({url}): every Airflow worker must reach the same staging, so set "
                             "PKF_STAGING_URL=s3://<bucket>/<prefix> on the workers (with a lifecycle rule) unless Airflow "
                             "runs on one machine"))
    return out


def lock_of(files: dict[str, bytes], name: str) -> dict:
    """The pipeline lock among render()'s files."""
    rel = next(r for r in files if r.endswith(f"/pkf/{name}/pipeline.lock.json"))
    return json.loads(files[rel])


def render(repo: Repo, name: str, *, allow_unapproved_code: bool = False) -> dict[str, bytes]:
    """Every generated file of the pipeline as bytes; nothing is written (see write). allow_unapproved_code: the draft
    build (K3) — the result is for review only and never written to the dags folder."""
    lock, modules = lock_for(repo, name, allow_unapproved_code=allow_unapproved_code)
    dags = settings(repo.root)["airflow"]["dags_folder"]
    dag = render_dag(lock)
    try:
        compile(dag, f"pkf_{name}.py", "exec")
    except SyntaxError as exc:  # a generator bug must never reach Airflow
        raise PfError(f"generated DAG for '{name}' is not valid Python ({exc}); please report", "internal") from None
    files = {f"{dags}/pkf_{name}.py": dag.encode(),
             f"{dags}/pkf/{name}/pipeline.lock.json": (json.dumps(lock, indent=2, sort_keys=True) + "\n").encode(),
             f"{dags}/.airflowignore": _airflowignore(repo.root / dags / ".airflowignore")}
    for rel, data in modules.items():
        files[f"{dags}/pkf/{name}/{rel}"] = data
    return files


def write(repo: Repo, files: dict[str, bytes], name: str) -> list[str]:
    dags = settings(repo.root)["airflow"]["dags_folder"]
    shutil.rmtree(repo.root / dags / "pkf" / name, ignore_errors=True)
    for rel, data in files.items():
        p = repo.root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    return sorted(files)


def check(repo: Repo, files: dict[str, bytes], name: str) -> list[str]:
    diffs = [f"{'missing' if not (repo.root / r).exists() else 'differs'}: {r}" for r, d in files.items()
             if not (repo.root / r).exists() or (repo.root / r).read_bytes() != d]
    dags = settings(repo.root)["airflow"]["dags_folder"]
    extra = repo.root / dags / "pkf" / name
    if extra.is_dir():
        diffs += [f"unexpected: {p.relative_to(repo.root).as_posix()}" for p in extra.rglob("*")
                  if p.is_file() and "__pycache__" not in p.parts and p.relative_to(repo.root).as_posix() not in files]
    return diffs


def orphans(repo: Repo) -> list[str]:
    """Generated files in the dags folder that belong to no current pipeline."""
    dags = settings(repo.root)["airflow"]["dags_folder"]
    root = repo.root / dags
    names = {p.stem for p in (repo.root / FOLDERS["pipeline"]).glob("*.yaml")}  # invalid specs keep their DAG
    out = [f"{dags}/{p.name}" for p in sorted(root.glob("pkf_*.py")) if p.stem[4:] not in names]
    if (root / "pkf").is_dir():
        out += [f"{dags}/pkf/{p.name}" for p in sorted((root / "pkf").iterdir()) if p.is_dir() and p.name not in names]
    return out
